const fs=require("node:fs"),assert=require("node:assert/strict"),cp=require("node:child_process");
const html=fs.readFileSync("index.html","utf8");
assert.match(html,/<script type="module" src="js\/application\.js"><\/script>/);
const paths=["js/application.js",...fs.readdirSync("js/classes").filter(x=>x.endsWith(".js")).map(x=>"js/classes/"+x)];
const js=paths.map(p=>{cp.execFileSync(process.execPath,["--input-type=module","--check"],{input:fs.readFileSync(p,"utf8")});return fs.readFileSync(p,"utf8")}).join("\n");
for(const mode of ["quiz","explore","memory","scene","position","placement"])assert.ok(html.includes('data-mode="'+mode+'"'),"Mode "+mode);
for(const id of ["oben","unten","links","rechts","mitte"])assert.ok(js.includes('id:"'+id+'"'),"Direction "+id);
assert.match(js,/positionObjects\[question\.object\]\.icon/,"All positions use the same object");
assert.doesNotMatch(js,/positionObjects\[objects\[i\]\]/);
assert.match(js,/if\(this\.positionAnswered\|\|state\.audioBusy\)return/);
assert.match(js,/playWrong\(word,options=\{\}\)/);
assert.match(js,/speak\("Falsch!",\{once:true,quick:1\.2,showWord:false,onEnd:playSelected\}\)/);
assert.match(js,/onEnd:replayTask/);
assert.match(js,/showWord\(word\)/);
assert.match(js,/showWord:false/);
assert.match(js,/toLocaleUpperCase/);
assert.match(js,/gameInstructions=\{/);
assert.match(js,/if\(options\.onEnd\)options\.onEnd\(\)/);
assert.match(html,/<details class="audioSettings">/);
assert.match(html,/id="rhymesButton"/);
for(const method of ["startMemory","finishGame","pictureMarkup","nextPosition","nextScene","setDifficulty","audioFile"])assert.ok(js.includes(method+"("),method);
assert.match(js,/player\.onerror/);
console.log("PASS: modular syntax and UX invariants; browser E2E is separate");
